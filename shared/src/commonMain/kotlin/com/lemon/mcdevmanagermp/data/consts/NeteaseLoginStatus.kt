package com.lemon.mcdevmanagermp.data.consts

private val recoverablePowerValidationCodes = setOf(803, 804, 805, 806)

fun neteaseLoginStatusCode(ret: Int, dt: String = ""): String {
    val detail = dt.trim()
    if (detail.isEmpty()) return ret.toString()
    return if (ret == 401 && detail in setOf("09", "10")) "$ret$detail" else "$ret-$detail"
}

fun isRecoverablePowerValidationCode(ret: Int): Boolean =
    ret in recoverablePowerValidationCodes

