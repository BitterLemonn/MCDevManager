private fun String?.toJsonObject(): JsonObject = runCatching {
    JSONConverter.parseToJsonElement(this.orEmpty()).jsonObject
}.getOrDefault(JsonObject(emptyMap()))

private fun String?.toJsonArray(): JsonArray = runCatching {
    JSONConverter.parseToJsonElement(this.orEmpty()).jsonArray
}.getOrElse {
    if (this.isNullOrEmpty()) JsonArray(emptyList()) else JsonArray(listOf(JsonPrimitive(this)))
}
